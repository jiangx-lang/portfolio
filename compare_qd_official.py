# 1. 从我们的 CSV 提取所有出现过的产品代码（拆开逗号）
df = pd.read_csv(CSV_PATH)
our_codes = set()
for v in df["sc_product_codes"].dropna():
    for c in str(v).split(","):
        c = c.strip()
        if c and c != "nan" and re.match(r"^(QDUR|QDUT)\d{3}[A-Z]{3}$", c):
            our_codes.add(c)

print(f"我们 CSV 中出现的唯一产品代码数: {len(our_codes)}")
print(f"我们 CSV 中唯一基金数 (fund_id): {df['fund_id'].nunique()}")

# 2. 官方代码：优先从文件读取，否则用内置列表
official_codes = set()
if Path(OFFICIAL_TABLE_PATH).exists():
    table_text = Path(OFFICIAL_TABLE_PATH).read_text(encoding="utf-8")
    official_codes = set(re.findall(r"(QDUR\d{3}[A-Z]{3}|QDUT\d{3}[A-Z]{3})", table_text))
    print(f"官方表（文件）中提取的产品代码数: {len(official_codes)}")
else:
    official_codes = set(re.findall(r"(QDUR\d{3}[A-Z]{3}|QDUT\d{3}[A-Z]{3})", OFFICIAL_CODES_BUILTIN))
    print(f"官方表（内置）产品代码数: {len(official_codes)}")

# 3. 缺失 = 在官方有、在我们没有
missing = official_codes - our_codes
extra = our_codes - official_codes  # 我们有但官方表没有的（可能是新上架或命名差异）

def base_code(c):
    return re.match(r"(QDUR\d{3}|QDUT\d{3})", c).group(1) if re.match(r"(QDUR|QDUT)\d{3}", c) else c

# 按基础代码汇总缺失（便于看“整只基金缺失”）
missing_by_base = {}
for c in sorted(missing):
    b = base_code(c)
    missing_by_base.setdefault(b, []).append(c)

print(f"\n官方有、我们 CSV 没有的代码数: {len(missing)}")
if missing:
    for c in sorted(missing):
        print(f"  缺失: {c}")
    print(f"\n按基础代码汇总（共 {len(missing_by_base)} 个基础代码有缺失）:")
    for b in sorted(missing_by_base):
        print(f"  {b}: {', '.join(missing_by_base[b])}")

print(f"\n我们 CSV 有、官方表未出现的代码数: {len(extra)}")
if extra and len(extra) <= 50:
    for c in sorted(extra):
        print(f"  我们有: {c}")
elif extra:
    print("  (数量较多，仅列出前30个)")
    for c in sorted(extra)[:30]:
        print(f"  我们有: {c}")

# 写出缺失列表到文件（UTF-8）
out_path = Path("qd_missing_codes.txt")
out_path.write_text(
    "官方有、我们 CSV 没有的 QD 产品代码\n"
    f"共 {len(missing)} 个\n\n"
    + "\n".join(sorted(missing))
    + "\n",
    encoding="utf-8",
)
print(f"\n缺失代码已写入: {out_path}")
