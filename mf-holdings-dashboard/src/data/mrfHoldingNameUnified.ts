/** 字符级繁体→简体 */
export function tradToSimplifiedHoldingName(s: string): string {
  let out = "";
  for (const ch of s) {
    out += TRAD_TO_SIMP_CHAR[ch] ?? ch;
  }
  return out;
}

function norm(s: string): string {
  return s.replace(/^\uFEFF/, "").replace(/\s+/g, " ").trim();
}

/**
 * 解析为标签表查找键：先精确/别名，再整串繁转简，再直接命中。
 */
export function resolveMrfHoldingTagLookupKey(raw: string): string {
  const t = norm(raw);
  if (!t) return t;
  if (MRF_HOLDING_RAW_TO_TAG_KEY[t]) return MRF_HOLDING_RAW_TO_TAG_KEY[t];
  const simp = tradToSimplifiedHoldingName(t);
  if (simp !== t && MRF_HOLDING_RAW_TO_TAG_KEY[simp]) return MRF_HOLDING_RAW_TO_TAG_KEY[simp];
  return simp;
}

/** 界面展示用简体名称 */
export function formatMrfHoldingDisplayName(raw: string): string {
  const t = norm(raw);
  if (!t) return t;
  const tagKey = resolveMrfHoldingTagLookupKey(t);
  const fromEn = EN_STOCK_DISPLAY_ZH[tagKey] ?? EN_STOCK_DISPLAY_ZH[t];
  if (fromEn) return fromEn;
  const simpRaw = tradToSimplifiedHoldingName(t);
  if (/[\u4e00-\u9fff]/.test(simpRaw)) return simpRaw;
  return t;
}
